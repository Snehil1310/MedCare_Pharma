import { DatabaseSync } from "node:sqlite";
import path from "path";
import fs from "fs";
import { fileURLToPath } from "url";

let db: DatabaseSync | null = null;
let alertIntervalStarted = false;

export function getDb(): DatabaseSync {
  if (db) return db;

  // Store DB file in a data/ directory at project root
  const projectRoot = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    "../.."
  );
  const dataDir = path.join(projectRoot, "data");
  if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
  }

  const dbPath = path.join(dataDir, "medcare.db");
  db = new DatabaseSync(dbPath);

  // Enable WAL mode for better concurrent performance
  db.exec("PRAGMA journal_mode = WAL;");
  db.exec("PRAGMA foreign_keys = ON;");

  // Run schema migration
  const schemaPath = path.join(
    path.dirname(fileURLToPath(import.meta.url)),
    "schema.sql"
  );
  const schema = fs.readFileSync(schemaPath, "utf-8");
  db.exec(schema);

  // Seed if the database is empty
  const count = db.prepare("SELECT COUNT(*) as c FROM kpis").get() as {
    c: number;
  };
  if (count.c === 0) {
    seedDatabase(db);
  }

  // Force clean up any buggy alerts generated by the previous interval and update existing recommendations
  db.exec("DELETE FROM alerts WHERE cause = 'Automated real-time telemetry';");
  db.exec("UPDATE alerts SET recommendation = 'Review immediately' WHERE severity = 'critical';");
  db.exec("UPDATE alerts SET recommendation = 'Review Fast' WHERE severity = 'high';");
  db.exec("UPDATE alerts SET recommendation = 'Review' WHERE severity = 'medium';");

  // Clean up any duplicate open alerts so the user only sees one of each type
  db.exec(`
    DELETE FROM alerts 
    WHERE id NOT IN (
      SELECT MIN(id) 
      FROM alerts 
      WHERE status = 'open' 
      GROUP BY title
    ) AND status = 'open';
  `);

  // Force update threshold limit label
  db.exec(`UPDATE settings_thresholds SET label = 'Auto-approval limit — ₹10,00,000' WHERE label LIKE 'Auto-approval limit%';`);

  // Seed pending_payments if empty (added later)
  const ppCount = db.prepare("SELECT COUNT(*) as c FROM pending_payments").get() as { c: number };
  if (ppCount.c === 0) {
    const insertPP = db.prepare(
      "INSERT INTO pending_payments (invoice_number, supplier, amount, due_date) VALUES (?, ?, ?, ?)"
    );
    const pps = [
      ["INV-9901", "MedSupply Pvt Ltd", "₹1,45,000", "28 Aug 2026"],
      ["INV-9905", "Supplier C", "₹64,200", "30 Aug 2026"],
      ["INV-9912", "Supplier B", "₹1,12,000", "02 Sep 2026"]
    ];
    for (const p of pps) insertPP.run(...p);
  }

  if (!alertIntervalStarted) {
    alertIntervalStarted = true;
    
    const scheduleNextAlert = () => {
      // Random interval between 1 and 8 minutes
      const randomIntervalMs = Math.floor(Math.random() * (8 * 60 * 1000 - 1 * 60 * 1000) + 1 * 60 * 1000);
      
      setTimeout(() => {
        try {
          if (!db) return;
          const insertAlert = db.prepare(
            "INSERT INTO alerts (severity, title, cause, impact, recommendation, owner, deadline) VALUES (?, ?, ?, ?, ?, ?, ?)"
          );
          const severities = ["medium", "high", "critical"];
          const severity = severities[Math.floor(Math.random() * severities.length)];
          
          let title = "";
          let cause = "";
          let impact = "";
          let rec = "";
          let owner = "";
          let deadline = "";

          if (severity === 'critical') {
            const tpls = [
              { t: "Stock-out predicted within 48 hours", c: "Sensed demand up 58% on flu-season signals in Tier-2 network", i: "₹6.8 L revenue at risk · service level drop to 82%", d: "1 hour" },
              { t: "Quality failure on incoming critical shipment", c: "Cold chain temperature breach during transit", i: "12,000 units compromised · immediate stock-out risk", d: "30 mins" },
              { t: "Recall issued for Lot #4829", c: "Regulatory advisory received from manufacturer", i: "Immediate removal required across 6 DCs", d: "2 hours" }
            ];
            const chosen = tpls[Math.floor(Math.random() * tpls.length)];
            title = chosen.t; cause = chosen.c; impact = chosen.i; deadline = chosen.d;
            rec = "Review immediately";
            owner = "Level 3 — Supply Chain Head";
          } else if (severity === 'high') {
            const tpls = [
              { t: "8,400 units approaching expiry", c: "Slow-moving batches in Metro DCs with 42–60 day shelf life", i: "₹4.1 L potential wastage", d: "4 hours" },
              { t: "Supplier lead time increased by 14 days", c: "Port congestion and raw material shortages", i: "Safety stock depletion over next 3 weeks", d: "6 hours" },
              { t: "Significant price variance detected", c: "Invoice INV-8392 exceeds PO by 18%", i: "Cost overrun of ₹1.2 L on current order", d: "8 hours" }
            ];
            const chosen = tpls[Math.floor(Math.random() * tpls.length)];
            title = chosen.t; cause = chosen.c; impact = chosen.i; deadline = chosen.d;
            rec = "Review Fast";
            owner = "Level 2 — Regional Manager";
          } else {
            const tpls = [
              { t: "Demand forecast changed by >20% for 12 SKUs", c: "Promotion calendar update + weather-driven signal shift", i: "Replenishment plan drift across 4 DCs", d: "12 hours" },
              { t: "Unusual movement detected in Tier-2 network", c: "Sudden spike in bulk orders from specific clinics", i: "Potential localized shortage if trend continues", d: "24 hours" },
              { t: "Pending transfers delayed", c: "Logistics partner reported vehicle breakdown", i: "2-day delay in stock rebalancing", d: "18 hours" }
            ];
            const chosen = tpls[Math.floor(Math.random() * tpls.length)];
            title = chosen.t; cause = chosen.c; impact = chosen.i; deadline = chosen.d;
            rec = "Review";
            owner = "Level 1 — Demand Planner";
          }
          
          // Prevent duplicate open alerts
          const existing = db.prepare("SELECT COUNT(*) as count FROM alerts WHERE title = ? AND status = 'open'").get(title) as { count: number };
          
          if (existing.count === 0) {
            insertAlert.run(severity, title, cause, impact, rec, owner, deadline);
          }
        } catch (e) {
          console.error("Failed to generate periodic alert", e);
        }
        
        // Schedule the next one recursively
        scheduleNextAlert();
      }, randomIntervalMs);
    };

    // Start the loop
    scheduleNextAlert();
  }

  return db;
}

